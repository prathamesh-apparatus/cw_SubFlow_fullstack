CREATE TABLE IF NOT EXISTS subscriptions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  category_id UUID NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
  name VARCHAR(255) NOT NULL,
  description TEXT,
  website_url TEXT,
  account_email VARCHAR(255) NOT NULL,
  account_username VARCHAR(255),
  price NUMERIC(12,2) NOT NULL DEFAULT 0,
  currency VARCHAR(10) NOT NULL DEFAULT 'INR',
  billing_cycle VARCHAR(20) NOT NULL DEFAULT 'monthly',
  custom_billing_days INTEGER,
  tax_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  total_amount NUMERIC(12,2) NOT NULL DEFAULT 0,
  payment_method VARCHAR(30),
  auto_pay_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  payment_status VARCHAR(20) NOT NULL DEFAULT 'pending',
  payment_notes TEXT,
  start_date DATE,
  last_payment_date DATE,
  next_renewal_date DATE,
  end_date DATE,
  renewal_reminder BOOLEAN NOT NULL DEFAULT TRUE,
  reminder_days_before INTEGER NOT NULL DEFAULT 7,
  status VARCHAR(20) NOT NULL DEFAULT 'active',
  auto_renewal_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT subscriptions_price_nonneg CHECK (price >= 0),
  CONSTRAINT subscriptions_tax_nonneg CHECK (tax_amount >= 0),
  CONSTRAINT subscriptions_total_nonneg CHECK (total_amount >= 0),
  CONSTRAINT subscriptions_billing_cycle_check CHECK (billing_cycle IN ('monthly','quarterly','half_yearly','yearly','custom')),
  CONSTRAINT subscriptions_custom_days_check CHECK ((billing_cycle <> 'custom') OR (custom_billing_days IS NOT NULL AND custom_billing_days > 0)),
  CONSTRAINT subscriptions_payment_status_check CHECK (payment_status IN ('paid','pending','failed')),
  CONSTRAINT subscriptions_payment_method_check CHECK (payment_method IS NULL OR payment_method IN ('credit_card','debit_card','upi','net_banking','other')),
  CONSTRAINT subscriptions_status_check CHECK (status IN ('active','inactive','cancelled','expired','trial')),
  CONSTRAINT subscriptions_reminder_days_check CHECK (reminder_days_before IN (3,7,15,30)),
  CONSTRAINT subscriptions_dates_check CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE TABLE IF NOT EXISTS payment_history (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  subscription_id UUID NOT NULL REFERENCES subscriptions(id) ON DELETE CASCADE,
  amount NUMERIC(12,2) NOT NULL,
  currency VARCHAR(10) NOT NULL DEFAULT 'INR',
  payment_date DATE NOT NULL,
  payment_method VARCHAR(30),
  payment_status VARCHAR(20) NOT NULL DEFAULT 'paid',
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT payment_history_amount_nonneg CHECK (amount >= 0),
  CONSTRAINT payment_history_status_check CHECK (payment_status IN ('paid','pending','failed'))
);
